import { existsSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export function readDeploymentConfig(env) {
    const required = (name) => {
        const value = env[name]?.trim();
        if (!value) throw new Error(`Set ${name} in .env or the build environment.`);
        return value;
    };
    const apiBaseUrl = required('API_BASE_URL').replace(/\/+$/, '');
    const url = new URL(apiBaseUrl);
    if (
        !['http:', 'https:'].includes(url.protocol) ||
        url.username ||
        url.password ||
        url.search ||
        url.hash
    ) {
        throw new Error(
            'API_BASE_URL must be an HTTP(S) URL without credentials, query or fragment.'
        );
    }
    return {
        API_BASE_URL: apiBaseUrl,
        firebaseConfig: {
            apiKey: required('FIREBASE_API_KEY'),
            authDomain: required('FIREBASE_AUTH_DOMAIN'),
            projectId: required('FIREBASE_PROJECT_ID'),
            appId: required('FIREBASE_APP_ID')
        }
    };
}

export async function configureExtension() {
    const envFile = resolve(root, '.env');
    if (existsSync(envFile)) process.loadEnvFile(envFile);
    const config = readDeploymentConfig(process.env);
    const output = resolve(root, 'app/client/build');
    await mkdir(output, { recursive: true });
    await writeFile(
        resolve(output, 'deployment_config.js'),
        '// Generated by scripts/configure-extension.mjs. Do not commit.\n' +
            `export const API_BASE_URL = ${JSON.stringify(config.API_BASE_URL)};\n` +
            `export const firebaseConfig = ${JSON.stringify(config.firebaseConfig, null, 4)};\n`
    );
    return config;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    await configureExtension();
}
